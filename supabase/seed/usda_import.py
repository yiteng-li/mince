#!/usr/bin/env python3
"""Builds the shared food database from USDA FoodData Central CSV downloads (public domain).

Download "SR Legacy" and "Foundation Foods" (CSV) from https://fdc.nal.usda.gov/download-datasets, then:

    python3 supabase/seed/usda_import.py FoodData_Central_sr_legacy_food_csv_*.zip FoodData_Central_foundation_food_csv_*.zip
    psql "$SUPABASE_DB_URL" -f supabase/seed/usda_foods.sql

Re-running is safe: rows are keyed by (source, source_id) and food ids are derived from the FDC id.
Nutrient ids come from the nutrients catalogue in the reference-data migration, so there is one mapping.
Standard library only.
"""
import csv
import io
import json
import re
import sys
import uuid
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = next((ROOT / "migrations").glob("*_reference_data.sql"))
OUT = Path(__file__).with_name("usda_foods.sql")
NS = uuid.UUID("6f1c0d7e-3b1a-4c7e-9a52-1d0c5b0e7a11")

# Fallback FDC ids when a dataset reports a nutrient under a different id (Foundation Foods does this).
FALLBACKS = {"energy": [2047, 2048], "carbs": [1050], "sugars": [1063], "ala": [1270], "la": [1269]}


def catalogue():
    """key -> fdc nutrient id, parsed from the reference migration."""
    rows = re.findall(r"\('([a-z0-9_]+)', '(?:[^']|'')*', '[a-zA-Z]+', '[a-z]+', \d+, (\d+|null)\)", REFERENCE.read_text())
    return {k: int(f) for k, f in rows if f != "null"}


def read_csv(z, name):
    member = next((m for m in z.namelist() if m.endswith("/" + name) or m == name), None)
    if member is None:
        return []
    with z.open(member) as fh:
        return list(csv.DictReader(io.TextIOWrapper(fh, encoding="utf-8")))


def num(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def build(zip_paths):
    key_by_fdc = {v: k for k, v in catalogue().items()}
    for key, ids in FALLBACKS.items():
        for i in ids:
            key_by_fdc.setdefault(i, "_" + key)  # fallback marker, used only when the primary id is missing

    foods = {}
    for path in zip_paths:
        with zipfile.ZipFile(path) as z:
            kept = {r["fdc_id"]: r for r in read_csv(z, "food.csv") if r.get("data_type") in ("sr_legacy_food", "foundation_food")}
            units = {r["id"]: r["name"] for r in read_csv(z, "measure_unit.csv")}
            for r in read_csv(z, "food_nutrient.csv"):
                fid = r["fdc_id"]
                if fid not in kept:
                    continue
                key = key_by_fdc.get(int(r["nutrient_id"]))
                amount = num(r["amount"])
                if key is None or amount is None:
                    continue
                f = foods.setdefault(fid, {"name": kept[fid]["description"].strip(), "n": {}, "fb": {}, "servings": []})
                (f["fb"] if key.startswith("_") else f["n"])[key.lstrip("_")] = amount
            for r in read_csv(z, "food_portion.csv"):
                f = foods.get(r["fdc_id"])
                grams, amount = num(r["gram_weight"]), num(r["amount"]) or 1
                if not f or not grams or grams <= 0:
                    continue
                label = (r.get("modifier") or "").strip()
                if not label or label.isdigit():
                    label = (r.get("portion_description") or "").strip() or units.get(r.get("measure_unit_id", ""), "")
                if not label or label == "undetermined":
                    continue
                name = f"{amount:g} {label}" if not re.match(r"^\d", label) else label
                f["servings"].append((name[:80], round(grams, 3), int(num(r.get("seq_num")) or 0)))

    out = []
    for fid, f in foods.items():
        n = f["n"]
        for k, v in f["fb"].items():
            n.setdefault(k, v)
        if "energy" not in n:
            if not any(k in n for k in ("protein", "carbs", "fat")):
                continue
            n["energy"] = round(4 * n.get("protein", 0) + 4 * n.get("carbs", 0) + 9 * n.get("fat", 0), 1)
        if "carbs" in n:
            n["net_carbs"] = round(max(n["carbs"] - n.get("fiber", 0), 0), 3)
        o3 = [n[k] for k in ("ala", "epa", "dha", "dpa") if k in n]
        o6 = [n[k] for k in ("la", "aa") if k in n]
        if o3:
            n["omega_3"] = round(sum(o3), 4)
        if o6:
            n["omega_6"] = round(sum(o6), 4)
        out.append((fid, f["name"], {k: round(v, 4) for k, v in n.items()}, sorted(set(f["servings"]), key=lambda s: s[2])))
    return out


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def write(foods):
    lines = ["-- Generated by usda_import.py from USDA FoodData Central (public domain). Do not edit by hand.", "begin;"]
    for i in range(0, len(foods), 500):
        chunk = foods[i:i + 500]
        lines.append("insert into public.foods (id, user_id, kind, source, source_id, name, nutrients) values")
        lines.append(",\n".join(
            f"  ('{uuid.uuid5(NS, fid)}', null, 'food', 'usda', '{fid}', {sql_str(name)}, {sql_str(json.dumps(n, separators=(',', ':')))}::jsonb)"
            for fid, name, n, _ in chunk))
        lines.append("on conflict (user_id, source, source_id) do update set name = excluded.name, nutrients = excluded.nutrients;")
    serving_rows = []
    for fid, _, _, servings in foods:
        for pos, (name, grams, _) in enumerate(servings[:12]):
            sid = uuid.uuid5(NS, f"{fid}:{name}:{grams}")
            serving_rows.append(f"  ('{sid}', '{uuid.uuid5(NS, fid)}', {sql_str(name)}, {grams}, {'true' if pos == 0 else 'false'}, {pos})")
    for i in range(0, len(serving_rows), 1000):
        lines.append("insert into public.food_servings (id, food_id, name, grams, is_default, position) values")
        lines.append(",\n".join(serving_rows[i:i + 1000]))
        lines.append("on conflict (id) do nothing;")
    lines.append("commit;")
    OUT.write_text("\n".join(lines) + "\n")
    return len(serving_rows)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    foods = build(sys.argv[1:])
    servings = write(foods)
    print(f"wrote {OUT.relative_to(ROOT.parent)}: {len(foods)} foods, {servings} servings")
